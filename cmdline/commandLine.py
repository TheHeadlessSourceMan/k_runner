class ArgView:
    """
    Just the args to a program, that is
    argv only without the program name.
    """
    def __init__(self,allArgs:"CommandLineArguments"):
        self.allArgs=allArgs

    def __iter__(self):
        """
        Access like an array of parameter strings
        """
        return self.allArgs[1:]

    def __len__(self):
        """
        Access like an array of parameter strings
        """
        return len(self.allArgs)-1

    @typing.overload
    def __getitem__(self,idx:slice)->typing.Iterable[str]:
        """
        Access like an array of parameter strings
        """
    @typing.overload
    def __getitem__(self,idx:int)->str:
        """
        Access like an array of parameter strings
        """
    def __getitem__(self,
        idx:typing.Union[int,slice]
        )->typing.Iterable[str]:
        """
        Access like an array of parameter strings
        """
        if isinstance(idx,slice):
            idx=slice(idx.start+1,idx.stop+1,idx.step)
        else:
            idx+=1
        return self.allArgs[idx]

    def __setitem__(self,idx:int,val:str)->None:
        """
        Access like an array of parameter strings
        """
        self.allArgs[idx+1]=val

    def __delitem__(self,idx:int)->None:
        """
        Access like an array of parameter strings
        """
        del self.allArgs[idx+1]


class CommandLineArguments:
    """
    Wrap command line arguments in a more useful way
    """
    def __init__(self,
        *allArgs:typing.Union[CommandLineCompatible,None],
        invalidOsChars:typing.Union[str,typing.Iterable[str],None]=None):
        """ """
        self._argv:typing.List[str]=[]
        if invalidOsChars is None:
            invalidOsChars=os.name
        if isinstance(invalidOsChars,str):
            if invalidOsChars=='nt':
                # TODO: do this better
                invalidOsChars=('&','|',';','@')
            else:
                invalidOsChars=('&','|',';','@')
        self.invalidOsChars:typing.Iterable[str]=invalidOsChars
        for args in allArgs:
            if args is not None:
                self.append(args)

    @property
    def args(self)->ArgView:
        """
        Just the args
        (that is, without the program name)

        You can still modify them and the
        results will be reflected in the output
        """
        return ArgView(self)

    @property
    def parameterInfo(self)->CommandLineParameterInfo:
        """
        Try and find information
        """
        return CommandLineParameterInfo(self)

    def __iter__(self)->typing.Iterator[str]:
        """
        Access like an array of parameter strings
        """
        return iter(self._argv)

    def __len__(self)->int:
        """
        Access like an array of parameter strings
        """
        return len(self._argv)

    @typing.overload
    def __getitem__(self,idx:slice)->typing.Iterable[str]:
        """
        Access like an array of parameter strings
        """
    @typing.overload
    def __getitem__(self,idx:int)->str:
        """
        Access like an array of parameter strings
        """
    def __getitem__(self,
        idx:typing.Union[int,slice]
        )->typing.Iterable[str]:
        """
        Access like an array of parameter strings
        """
        return self._argv[idx]

    def __setitem__(self,idx:int,val:str)->None:
        """
        Access like an array of parameter strings
        """
        self._argv[idx]=val

    def __delitem__(self,idx:int)->None:
        """
        Access like an array of parameter strings
        """
        del self._argv[idx]

    def runAsync(self,
        shell:bool=False,
        detach:bool=False,
        debug:bool=False,
        workingDirectory:typing.Union[None,str,Path]=None,
        environmentVariables:typing.Optional[
            EnvironmentVariablesCompatible]=None,
        runCallbacks:typing.Optional[DataRecievedCallbacks]=None,
        priority:float=0.5,
        ansiHandling:str="strip",
        showHidden:bool=False,
        showMinimized:bool=False,
        showMaximized:bool=False,
        env:typing.Optional[
            EnvironmentVariablesCompatible]=None # alias for compatability
        )->"OsRunJob":
        """
        Generally speaking, this is backwards and you
        should osRun(commandline) instead.
        """
        from k_runner import OsRun
        job=OsRun(self,
            shell=shell,detach=detach,debug=debug,
            workingDirectory=workingDirectory,
            environmentVariables=environmentVariables,
            runCallbacks=runCallbacks,
            priority=priority,
            ansiHandling=ansiHandling,
            showHidden=showHidden,
            showMinimized=showMinimized,
            showMaximized=showMaximized,
            env=env).runAsync()
        return job

    def run(self,
        shell:bool=False,
        detach:bool=False,
        debug:bool=False,
        workingDirectory:typing.Union[None,str,Path]=None,
        environmentVariables:typing.Optional[
            EnvironmentVariablesCompatible]=None,
        runCallbacks:typing.Optional[DataRecievedCallbacks]=None,
        priority:float=0.5,
        ansiHandling:str="strip",
        showHidden:bool=False,
        showMinimized:bool=False,
        showMaximized:bool=False,
        env:typing.Optional[
            EnvironmentVariablesCompatible]=None # alias for compatability
        )->"OsRunResult":
        """
        Generally speaking, this is backwards and you
        should osRun(commandline) instead.
        """
        from k_runner import OsRun
        result=OsRun(self,
            shell=shell,detach=detach,debug=debug,
            workingDirectory=workingDirectory,
            environmentVariables=environmentVariables,
            runCallbacks=runCallbacks,
            priority=priority,
            ansiHandling=ansiHandling,
            showHidden=showHidden,
            showMinimized=showMinimized,
            showMaximized=showMaximized,
            env=env).run()
        return result
    __call__=run

    @property
    def name(self)->str:
        """
        The name of the executable
        """
        if not self._argv:
            return ''
        return self._argv[0]
    @name.setter
    def name(self,name:str):
        if not self._argv:
            self._argv.append(name)
        else:
            self._argv[0]=name

    def append(self,args:typing.Union[CommandLineCompatible,None]=None):
        """
        Add more arguments to the command line
        """
        if args is None:
            return
        if hasattr(args,'args') and not isinstance(args,CommandLine):
            args=typing.cast(CommandLineCompatible,args.args) # type: ignore
        if isinstance(args,Path):
            args=str(args)
        elif isinstance(args,str):
            p,a=commandlineSplit(args)
            args=[p]
            args.extend(a)
        if not isinstance(args,(list,tuple,CommandLine)):
            raise NotImplementedError(f'WARN: coercing type "{type(args)}" to a command line is not yet supported!') # noqa: E501 # pylint: disable=line-too-long
        for arg in args: # type: ignore
            self._argv.append(arg) # type: ignore
    extend=append

    def assign(self,args:typing.Union[CommandLineCompatible,None]=None):
        """
        Change the arguments
        """
        self.clear()
        self.append(args)

    def clear(self)->None:
        """
        Clear the arguments
        """
        self._argv.clear()

    def commandLineArgs(self,shellReplace:bool=False)->typing.Iterable[str]:
        """
        Get command line args list of values.
        """
        if shellReplace:
            try:
                import osTools
                args=osTools.expandvars(self._argv)
            except ImportError as e:
                print(e)
        args=self._argv
        return [self._shellEscape(arg) for arg in args]

    def asString(self,
        shellReplace:bool=False
        )->str:
        """
        Get as a string
        """
        args=self.commandLineArgs(shellReplace)
        return ' '.join([self._enquote(arg) for arg in args])
    toString=asString

    def _enquote(self,s:str)->str:
        if ' ' in s:
            s=s.replace('\\\\','\\').replace('"','\\"')
            return f'"{s}"'
        return s

    def _shellEscape(self,s:str)->str:
        """
        Shell escape the args
        """
        if isinstance(s,Path):
            return s # This is good by definition
        s=str(s)
        for c in self.invalidOsChars:
            s=s.replace(c,'\\'+c)
        return s

    def encodeToArray(self)->typing.List[str]:
        """
        In preparation for calling, this encodes all of the
        values to an array of shell-escaped values.
        """
        return [self._shellEscape(v) for v in self._argv]

    def __repr__(self)->str:
        return self.asString()
