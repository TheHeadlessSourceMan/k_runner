def main(args:typing.Iterable[str])->int:
    """
    This generates a command line wrapper... from the command line.
    """
    printHelp=False
    cmd=None
    infoFrom:typing.List[str]=[]
    out:typing.List[str]=[]
    for arg in args:
        if cmd is None:
            if arg[0]=='-':
                if arg[1]=='-':
                    arg=arg.split('=',1)
                    if arg[0]=='--out':
                        out.append(arg[-1])
                    else:
                        print('Unrecognized parameter: '+arg[0])
                        printHelp=True
                else:
                    print('Unrecognized parameter: '+arg)
                    printHelp=True
            else:
                cmd=arg
        else:
            infoFrom.append(arg)
    if cmd is None:
        print('ERR: no cmd specified.')
        printHelp=True
    if len(out)<1:
        print('ERR: no outputs specified.')
        printHelp=True
    if printHelp:
        print('USAGE:')
        print('\tcommandLine.py --out=filename [--out=filename ...] cmd [get_info_from]') # noqa: E501 # pylint: disable = line-too-long
        print('PARAMS:')
        print('\t--out=<filename> ..... output to save.  If filename is just an extension, save to stdout.') # noqa: E501 # pylint: disable = line-too-long
        print('\t\tcurrently supports: only ".py"')
        print('EXAMPLES:')
        print('\tAutomatically generate python wrapper for "ls" to the file "ls.py":') # noqa: E501 # pylint: disable = line-too-long
        print('\t\tcommandLine.py --out=ls.py ls')
        print('\tAutomatically generate python wrapper for "ls" to stdout:')
        print('\t\tcommandLine.py --out=.py ls')
        print('\tGenerate the wrapper by calling the command with --help:')
        print('\t\tcommandLine.py --out=.py ls ls --help')
        print('\t... or just let commandLine make the assumption:')
        print('\t\tcommandLine.py --out=.py ls --help')
        print('\tGenerate the wrapper from the command\'s manpage:')
        print('\t\tcommandLine.py --out=.py ls man')
        print('\tGenerate the wrapper from a webpage:')
        print('\t\tcommandLine.py --out=.py ls http://www.foo.com/ls.html')
        print('\t... or a local file:')
        print('\t\tcommandLine.py --out=.py ls ls.html')
        print('\t... same goes for text files:')
        print('\t\tcommandLine.py --out=.py ls README.txt')
        return -1
    wrapper=CmdLineParameterInfo(cmd)
    wrapper.getCommandLineOptions(' '.join(infoFrom))
    for o in out:
        extension=o.rsplit('.',1)
        if extension[-1]=='py':
            if len(extension)<2 or extension[0]=='' or extension[0]=='-':
                print(wrapper.createPythonWrapper(createMainFunction=True))
            else:
                wrapper.savePythonWrapper(o,createMainFunction=True)
    return 0


if __name__ == '__main__':
    import sys
    sys.exit(main(sys.argv[1:]))
