class CommandLineWrapper(HelpSystemEntry):
    """
    A tool to create function calls from command line apps
    """
    def __init__(self,
        app:typing.Optional[CommandLineCompatible]=None):
        HelpSystemEntry.__init__(self,app)

    @typing.overload
    def __getitem__(self,idx:slice)->list[CommandLineOption]:
        ...
    @typing.overload
    def __getitem__(self,idx:int)->CommandLineOption:
        ...
    def __getitem__(self,idx:typing.Union[int,slice]
        )->typing.Union[CommandLineOption,list[CommandLineOption]]:
        return self.commandLineOptions[idx]

    def createPythonWrapperCode(self,
        createMainFunction:bool=False,
        tabFormat:str='    '
        )->str:
        """
        Create python code (in a string) that wraps the command line call

        :createMainFunction: Generally, creating a command line
            app to call a command line app is
            rather pointless.  Still, can be handy for testing.
        """
        opts=tuple(self.getCommandLineOptions())
        if len(opts)<1:
            return ''
        code:typing.List[str]=[]
        code.append('#!/usr/bin/python')
        code.append('"""')
        code.append(f'This is wrapper for the "{self.name}" command line program') # noqa: E501 # pylint: disable = line-too-long
        if self.description:
            code.append('')
            for line in self.getDescription(False,True).split('\n'):
                code.append(line)
        code.append('')
        code.append('Generated by: The commandLine.py utility')
        code.append('"""')
        code.append('\n')
        code.append(f'def {self.name}(*args,**kwargs):')
        code.append(f'def {self.name}(*args,**kwargs):')
        code.append('\t"""')
        if self.description:
            code.append('\tDESCRIPTION:')
            for line in self.getDescription(False,True).split('\n'):
                code.append('\t\t'+line)
        code.append('\tPARAMETERS:')
        for o in opts:
            code.append('\t\t'+o.getHelp())
        code.append('\tRETURNS:')
        code.append('\t\tout,err')
        code.append('\t"""')
        code.append('\toptions={')
        for o in opts:
            opt=''
            for opt in o.options:
                break
            opt=opt.replace('[','').replace(']','')
            code.append('\t\t\''+o.name+'\':[\''+opt+'\'],')
        code.append('\t}')
        # TODO: May want to check if the app exists first??
        code.append(f'\tcmd=\'{self.app}\'')
        code.append('\tfor k,v in kwargs.items():')
        code.append('\t\tif options.has_key(k):')
        code.append('\t\t\to=options[k][0].split(\'=\',1)')
        code.append('\t\t\tcmd=cmd+\' \'+o[0]')
        code.append('\t\t\tif len(o)>1:')
        code.append('\t\t\t\tif type(v)==list:')
        code.append('\t\t\t\t\tcmd=cmd+\'="\'+(\' \'.join(v))+\'"\'')
        code.append('\t\t\t\telif v is not None:')
        code.append('\t\t\t\t\tcmd=cmd+\'=\'+str(v)')
        code.append('\t\t\telse:')
        code.append('\t\t\t\tif type(v)==list:')
        code.append('\t\t\t\t\tcmd=cmd+\' \'+(\' \'.join(v))')
        code.append('\t\t\t\telif v is not None:')
        code.append('\t\t\t\t\tcmd=cmd+str(v)')
        code.append('\t\telse:')
        code.append('\t\t\tprint \'WARN: Unregistered arg: \'+k')
        code.append('\tif len(args)>0:')
        code.append('\t\tcmd=cmd+\' \'+(\' \'.join(args))')
        # TODO: Add any option parameters here
        code.append('\tprint \'Calling: \\n   \'+cmd # Uncomment for debugging purposes') # noqa: E501 # pylint: disable = line-too-long
        code.append('\timport subprocess')
        code.append('\tout,err=subprocess.Popen(cmd,stderr=subprocess.PIPE,stdout=subprocess.PIPE,shell=True).communicate()') # noqa: E501 # pylint: disable = line-too-long
        code.append('\treturn out,err')
        if createMainFunction:
            code.append('\n')
            code.append('if __name__ == \'__main__\':')
            code.append('\timport sys')
            code.append('\titems=[]')
            code.append('\toptions={}')
            code.append('\ttry: # in newer python, we can preserve argument ordering!') # noqa: E501 # pylint: disable = line-too-long
            code.append('\t\tfrom collections import OrderedDict')
            code.append('\t\toptions=OrderedDict()')
            code.append('\texcept:')
            code.append('\t\tpass')
            code.append('\tdef AddOption(opt):')
            code.append('\t\topt=opt.split(\'=\',1)')
            code.append('\t\tif len(opt)>1:')
            code.append('\t\t\toptions[opt[0]]=opt[1]')
            code.append('\t\telse:')
            code.append('\t\t\toptions[opt[0]]=None')
            code.append('\tfor arg in sys.argv[1:]:')
            code.append('\t\tif arg[0]==\'-\':')
            code.append('\t\t\tif arg[1]==\'-\':')
            code.append('\t\t\t\tAddOption(arg[2:])')
            code.append('\t\t\telse:')
            code.append('\t\t\t\tfor a in arg[1:]:')
            code.append('\t\t\t\t\tAddOption(a)')
            code.append('\t\telse:')
            code.append('\t\t\titems.append(arg)')
            code.append(f'\tout,err={self.name}(*items,**options)')
            code.append('\terr=err.strip()')
            code.append('\tif err!=\'\':')
            code.append('\t\tprint err')
            code.append('\telse:')
            code.append('\t\tprint out')
        return '\n'.join(code).replace('\t',tabFormat)
    createPythonWrapper=createPythonWrapperCode

    def savePythonWrapper(self,
        filename:UrlCompatible,
        createMainFunction:bool=False
        )->bool:
        """
        Create a python wrapper for the command line application
        and save it to file
        """
        filename=asUrl(filename)
        data=self.createPythonWrapper(createMainFunction=createMainFunction)
        if data:
            filename.write(data)
            return True
        print('ERR: No data found.  File not saved.')
        return False
